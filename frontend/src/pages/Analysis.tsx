import { useRef, useState } from 'react'
import { Link, useParams, useSearchParams } from 'react-router-dom'
import { mainApiClient } from '../api/mainApiClient'
import { toApiError, type ApiError } from '../api/http'
import { Card, DataNotice, ErrorState, KeyValueList, PageHeader, Pill, RiskPill } from '../components/ui'
import { OutcomePanel } from '../components/customer'
import { labelize, num, pct, splitInsights } from '../format'
import type { AnalysisResponse } from '../types/main'

const prioTone = { high: 'high', medium: 'medium', low: 'low' } as const

export default function Analysis() {
  const { id = '' } = useParams()
  const [params] = useSearchParams()
  const snapshotDate = params.get('snapshot_date')
  const [result, setResult] = useState<AnalysisResponse | null>(null)
  const [error, setError] = useState<ApiError | null>(null)
  const [loading, setLoading] = useState(false)
  const inFlight = useRef(false) // blocks duplicate clicks even before React re-renders

  async function run() {
    if (inFlight.current) return
    inFlight.current = true
    setLoading(true); setError(null)
    try {
      setResult(await mainApiClient.analyzeCustomer(id, snapshotDate))
    } catch (e) {
      setError(toApiError(e))
    } finally {
      inFlight.current = false
      setLoading(false)
    }
  }

  const r = result
  const llmOk = r?.llm_metadata.status === 'available'
  const detailLink = `/customers/${encodeURIComponent(id)}${snapshotDate ? `?snapshot_date=${snapshotDate}` : ''}`

  return (
    <>
      <p className="crumb"><Link to={detailLink}>← Customer details</Link></p>
      <PageHeader
        title={`AI analysis · ${id}`}
        subtitle={snapshotDate ? `Snapshot ${snapshotDate}` : 'Latest snapshot'}
        actions={<button className="btn primary" onClick={run} disabled={loading} aria-busy={loading}>{loading ? 'Analyzing…' : r ? 'Analyze again' : 'Analyze'}</button>}
      />
      {!r && !loading && !error && (
        <Card><p className="muted">Select Analyze to send this customer's snapshot and rule-based assessment to the language model. Each run can take several seconds and may create a monitoring event.</p></Card>
      )}
      {loading && <div className="state" role="status"><p>Waiting for the Main API and the model. This usually takes a few seconds.</p></div>}
      {error && <ErrorState error={error} onRetry={run} title={error.status === 404 ? 'Customer or snapshot not found' : 'Analysis failed'} />}

      {r && (
        <>
          <DataNotice text={r.data_notice} />

          <Card title="Rule-based risk assessment" caption={`Computed by transparent rules (${r.risk_assessment.risk_score_unit}); separate from the narrative below.`}>
            <div className="inline">
              <RiskPill category={r.risk_assessment.risk_category} />
              <strong>{r.risk_assessment.risk_score} points</strong>
              <span className="muted">{r.risk_assessment.risk_factors.length} risk factors · snapshot {r.snapshot_date}</span>
              <Link to={detailLink}>View factors</Link>
            </div>
          </Card>

          {!llmOk && (
            <div className="notice warn" role="alert">
              <strong>Fallback narrative, not AI-generated.</strong> The language model was unavailable
              {r.llm_metadata.error_category ? ` (${r.llm_metadata.error_category})` : ''}, so the text below is a rule-based fallback.
            </div>
          )}

          <Card title={llmOk ? 'AI-generated explanation' : 'Rule-based fallback explanation'} caption={llmOk ? `Generated by ${r.llm_metadata.provider} · ${r.llm_metadata.model}. It explains the supplied data and is not verified for correctness.` : 'Produced by the backend without the model.'}>
            <h3>Executive summary</h3>
            <p>{r.executive_summary}</p>
            <h3>Customer insights</h3>
            <ul>{splitInsights(r.customer_insights).map((t, i) => <li key={i}>{t}</li>)}</ul>
          </Card>

          <Card title="Retention recommendations" caption="Suggested actions for staff to consider. They are not automated decisions.">
            <div className="recs">
              {r.retention_recommendations.map((rec, i) => (
                <article className="rec" key={i}>
                  <div className="rec-head"><Pill tone={prioTone[rec.priority] ?? 'neutral'}>{rec.priority} priority</Pill><span className="muted small">Owner: {rec.suggested_owner}</span></div>
                  <h3>{rec.action}</h3>
                  <p className="muted">{rec.rationale}</p>
                  <p className="small"><strong>Success indicator:</strong> {rec.success_indicator}</p>
                </article>
              ))}
            </div>
          </Card>

          <div className="grid g2">
            <Card title="Model request details">
              <KeyValueList items={[
                ['Provider', r.llm_metadata.provider],
                ['Model', r.llm_metadata.model],
                ['Status', <Pill tone={llmOk ? 'low' : 'warn'}>{r.llm_metadata.status}</Pill>],
                ['Latency', r.llm_metadata.latency_ms == null ? '—' : `${num(r.llm_metadata.latency_ms, 0)} ms`],
                ['Prompt tokens', num(r.llm_metadata.token_usage?.prompt_tokens)],
                ['Completion tokens', num(r.llm_metadata.token_usage?.completion_tokens)],
                ['Total tokens', num(r.llm_metadata.token_usage?.total_tokens)],
                ['Reasoning tokens', num(r.llm_metadata.token_usage?.reasoning_tokens)],
                ['Request ID', <code>{r.llm_metadata.request_id}</code>],
                ['Error category', r.llm_metadata.error_category ?? 'None'],
              ]} />
            </Card>
            <Card title="Monitoring delivery" caption="Whether the Main API delivered this request to the separate Monitoring service. Confirm stored records on the Monitoring page.">
              <KeyValueList items={[
                ['Delivery', <Pill tone={r.monitoring.delivery_status === 'recorded' ? 'low' : 'warn'}>{r.monitoring.delivery_status}</Pill>],
                ['Delivery error', r.monitoring.error_category ?? 'None'],
                ['Prediction ID', <code>{r.monitoring.prediction_id}</code>],
                ['Evaluation status', labelize(r.monitoring.evaluation_status)],
                ['Rule alert matches 30-day outcome', r.monitoring.rule_alert_match_30d == null ? 'Not applicable' : r.monitoring.rule_alert_match_30d ? 'Yes' : 'No'],
                ['Explanation correctness', labelize(r.monitoring.llm_correctness_status)],
              ]} />
              {r.monitoring.llm_correctness_status === 'not_evaluated' && <p className="caption">“Not evaluated” means no independent review has happened. It does not mean the recommendations are correct.</p>}
            </Card>
          </div>

          <div className="grid g2">
            <Card title="Segment context" caption="Historical synthetic association only; not causal.">
              <KeyValueList items={[
                ['Segment', r.segment_comparison.customer_segment],
                ['Customers in segment', num(r.segment_comparison.customers_in_segment)],
                ['Segment historical churn rate', pct(r.segment_comparison.segment_historical_churn_rate, 2)],
                ['Overall historical churn rate', pct(r.segment_comparison.overall_historical_churn_rate, 2)],
              ]} />
              <p className="small muted">{r.segment_comparison.interpretation}</p>
            </Card>
            <OutcomePanel outcome={r.historical_outcome} />
          </div>

          <Card title="Limitations">
            <ul className="small muted">{r.limitations.map((l) => <li key={l}>{l}</li>)}</ul>
          </Card>
        </>
      )}
    </>
  )
}
